
BEGIN;

-- =========================================
-- ROLES
-- =========================================

CREATE TABLE roles (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name TEXT NOT NULL CHECK (btrim(name) <> ''),
    app_id TEXT NOT NULL CHECK (btrim(app_id) <> ''),
    UNIQUE (name, app_id)
);


-- =========================================
-- USERS
-- =========================================

CREATE TABLE users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name TEXT NOT NULL CHECK (btrim(name) <> ''),
    email TEXT NOT NULL CHECK (btrim(email) <> ''),
    password TEXT NOT NULL CHECK (password <> ''),
    role_id BIGINT REFERENCES roles(id) ON DELETE RESTRICT,
    phone TEXT,
    profile_picture TEXT,
    is_public BOOLEAN NOT NULL DEFAULT FALSE,
    is_enable BOOLEAN NOT NULL DEFAULT TRUE,
    email_verified_at TIMESTAMPTZ
);

CREATE UNIQUE INDEX users_email_lower_uq
ON users (lower(email));

CREATE INDEX users_role_id_idx
ON users(role_id);


-- =========================================
-- MUSCLES
-- =========================================

CREATE TABLE muscles (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name TEXT NOT NULL UNIQUE CHECK (btrim(name) <> '')
);


-- =========================================
-- EXERCISES
-- =========================================

CREATE TABLE exercises (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name TEXT NOT NULL CHECK (btrim(name) <> ''),
    image TEXT,
    muscle_1_id BIGINT NOT NULL REFERENCES muscles(id) ON DELETE RESTRICT,
    muscle_2_id BIGINT REFERENCES muscles(id) ON DELETE RESTRICT,
    muscle_3_id BIGINT REFERENCES muscles(id) ON DELETE RESTRICT,
    user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE RESTRICT,
    is_public BOOLEAN NOT NULL DEFAULT FALSE,

    CONSTRAINT exercise_muscle_1_2_distinct
        CHECK (muscle_2_id IS NULL OR muscle_1_id <> muscle_2_id),

    CONSTRAINT exercise_muscle_1_3_distinct
        CHECK (muscle_3_id IS NULL OR muscle_1_id <> muscle_3_id),

    CONSTRAINT exercise_muscle_2_3_distinct
        CHECK (
            muscle_2_id IS NULL
            OR muscle_3_id IS NULL
            OR muscle_2_id <> muscle_3_id
        )
);

CREATE INDEX exercises_user_id_idx
ON exercises(user_id);

CREATE INDEX exercises_muscle_1_id_idx
ON exercises(muscle_1_id);

CREATE INDEX exercises_muscle_2_id_idx
ON exercises(muscle_2_id)
WHERE muscle_2_id IS NOT NULL;

CREATE INDEX exercises_muscle_3_id_idx
ON exercises(muscle_3_id)
WHERE muscle_3_id IS NOT NULL;


-- =========================================
-- WORKOUT TEMPLATES
-- =========================================

CREATE TABLE workout_templates (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name TEXT NOT NULL CHECK (btrim(name) <> ''),
    user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE RESTRICT,
    is_public BOOLEAN NOT NULL DEFAULT FALSE
);

CREATE INDEX workout_templates_user_id_idx
ON workout_templates(user_id);


-- =========================================
-- WORKOUT TEMPLATE EXERCISES
-- =========================================

CREATE TABLE workout_template_exercises (
    workout_template_id BIGINT NOT NULL REFERENCES workout_templates(id) ON DELETE CASCADE,
    exercise_id BIGINT NOT NULL REFERENCES exercises(id) ON DELETE RESTRICT,
    position INTEGER NOT NULL CHECK (position > 0),

    PRIMARY KEY (workout_template_id, position),
    UNIQUE (workout_template_id, exercise_id)
);

CREATE INDEX workout_template_exercises_exercise_id_idx
ON workout_template_exercises(exercise_id);


-- =========================================
-- FAVORITES
-- =========================================

CREATE TABLE favorites (
    user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    workout_template_id BIGINT NOT NULL REFERENCES workout_templates(id) ON DELETE CASCADE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

    PRIMARY KEY (user_id, workout_template_id)
);

CREATE INDEX favorites_workout_template_id_idx
ON favorites(workout_template_id);


-- =========================================
-- FRIENDS
-- =========================================

CREATE TABLE friends (
    user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    friend_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

    PRIMARY KEY (user_id, friend_id),

    CONSTRAINT friends_no_self
        CHECK (user_id <> friend_id)
);

CREATE INDEX friends_friend_id_idx
ON friends(friend_id);


-- =========================================
-- WORKOUT SESSIONS
-- =========================================

CREATE TABLE workout_sessions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE RESTRICT,
    workout_template_id BIGINT NOT NULL REFERENCES workout_templates(id) ON DELETE RESTRICT,
    date_of_workout TIMESTAMPTZ NOT NULL,
    is_end BOOLEAN NOT NULL DEFAULT FALSE
);

CREATE INDEX workout_sessions_user_date_idx
ON workout_sessions(user_id, date_of_workout DESC);

CREATE INDEX workout_sessions_workout_template_id_idx
ON workout_sessions(workout_template_id);


-- =========================================
-- PERFORMANCE STATUSES
-- =========================================

CREATE TABLE performance_statuses (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name TEXT NOT NULL UNIQUE CHECK (btrim(name) <> '')
);

INSERT INTO performance_statuses (name) VALUES
    ('pending'),
    ('completed'),
    ('failed');


-- =========================================
-- PERFORMANCES
-- =========================================

CREATE TABLE performances (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    workout_session_id BIGINT NOT NULL REFERENCES workout_sessions(id) ON DELETE CASCADE,
    exercise_id BIGINT NOT NULL REFERENCES exercises(id) ON DELETE RESTRICT,
    status_id BIGINT REFERENCES performance_statuses(id) ON DELETE RESTRICT,
    weight NUMERIC(8, 2) CHECK (weight >= 0),
    rep INTEGER CHECK (rep >= 0),
    time_seconds INTEGER CHECK (time_seconds >= 0),
    rest_seconds INTEGER CHECK (rest_seconds >= 0)
);

CREATE INDEX performances_workout_session_id_idx
ON performances(workout_session_id);

CREATE INDEX performances_exercise_id_idx
ON performances(exercise_id);

CREATE INDEX performances_status_id_idx
ON performances(status_id);

COMMIT;
